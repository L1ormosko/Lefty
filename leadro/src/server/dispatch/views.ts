import type { DispatchRecommendation, Prisma } from "@prisma/client";
import { SCORING_VERSION, type RankedCandidate } from "@/lib/dispatch-scoring";
import type { EligibilityFailure } from "@/lib/eligibility";
import type { ResourceRef } from "@/server/authz";
import { employeeScopeColumns, enforceInTx, scopeFilterInTx } from "@/server/authz";
import { NotFoundError, type Actor } from "@/server/core";
import type { TenantTx } from "@/server/db";
import { jobResourceRef } from "@/server/jobs";

/**
 * How a stored recommendation is stored and shown. The JSON columns hold IDS and CODES only (ERD "Contracts for
 * JSON"). On READ every employee id is re-checked against the VIEWER's employee scope (`employees.view`): ids the viewer
 * may not see are dropped and only counted (`hiddenCandidateCount`), so a recommendation generated by a wider-scoped
 * colleague never shows a narrower-scoped viewer people or HR facts outside their scope.
 */

/** Always attached so a distance is never mistaken for travel time (§28.3). i18n key `DISPATCH.STRAIGHT_LINE_ESTIMATE`. */
export const DISTANCE_BASIS = "STRAIGHT_LINE_ESTIMATE";

export type BlockingReasons = Record<string, EligibilityFailure[]>;

/** The `DispatchRecommendation.candidates` column: the ranking plus what was and was not evaluated. */
export interface StoredCandidates {
  scoringVersion: number;
  /** Every assignment row of the job when this was generated (ids) and which were ACTIVE: the clock-free staleness baseline. */
  assignmentSnapshot?: { all: string[]; active: string[] };
  /** Employees judged for the generator (the pool after the SQL pre-filter and the generator's scope). */
  evaluatedCount: number;
  /** Relevant employees outside the generator's scope: counted, never listed. */
  outOfScopeCount: number;
  /** Visible employees with neither a territory covering the job's area nor a permission for its type (not candidates). */
  notRelevantCount: number;
  /** True when the evaluation ceiling stopped the pass: the ranking may be incomplete and "nobody eligible" is not proven. */
  poolTruncated: boolean;
  ranked: RankedCandidate[];
}

export interface RecommendationView {
  id: string;
  jobId: string;
  mode: string;
  status: string;
  scoringVersion: number;
  /** Ranked candidates the VIEWER may see. */
  candidates: RankedCandidate[];
  /** Why people were not eligible (stored only when nobody was and the pool was complete). Null otherwise. */
  blockingReasons: BlockingReasons | null;
  evaluatedCount: number;
  /** Relevant employees outside the generator's scope that were not evaluated for them. */
  outOfScopeCount: number;
  notRelevantCount: number;
  /** Candidates and blocked employees dropped from this view because the viewer may not see them. */
  hiddenCandidateCount: number;
  poolTruncated: boolean;
  distanceBasis: typeof DISTANCE_BASIS;
  generatedAt: Date;
  generatedById: string | null;
  chosenEmployeeId: string | null;
  decidedAt: Date | null;
  decidedById: string | null;
  decisionReason: string | null;
}

/** The stored column, tolerant of a missing envelope. */
export function storedCandidates(row: Pick<DispatchRecommendation, "candidates">): StoredCandidates {
  const raw = row.candidates as unknown;
  // Rows written before the envelope existed hold the bare ranked array.
  if (Array.isArray(raw)) return { scoringVersion: 0, evaluatedCount: raw.length, outOfScopeCount: 0, notRelevantCount: 0, poolTruncated: false, ranked: raw as RankedCandidate[] };
  const stored = raw as StoredCandidates;
  return { ...stored, notRelevantCount: stored.notRelevantCount ?? 0 };
}

export function recommendationView(row: DispatchRecommendation, visibleEmployeeIds: ReadonlySet<string>): RecommendationView {
  const stored = storedCandidates(row);
  const blocking = row.blockingReasons as unknown as BlockingReasons | null;
  const candidates = stored.ranked.filter((candidate) => visibleEmployeeIds.has(candidate.employeeId));
  const visibleBlocking = blocking ? Object.fromEntries(Object.entries(blocking).filter(([employeeId]) => visibleEmployeeIds.has(employeeId))) : null;
  const blockingTotal = blocking ? Object.keys(blocking).length : 0;
  return {
    id: row.id,
    jobId: row.jobId,
    mode: row.mode,
    status: row.status,
    scoringVersion: stored.scoringVersion,
    candidates,
    blockingReasons: visibleBlocking,
    evaluatedCount: stored.evaluatedCount,
    outOfScopeCount: stored.outOfScopeCount,
    notRelevantCount: stored.notRelevantCount,
    hiddenCandidateCount: stored.ranked.length - candidates.length + (blockingTotal - Object.keys(visibleBlocking ?? {}).length),
    poolTruncated: stored.poolTruncated,
    distanceBasis: DISTANCE_BASIS,
    generatedAt: row.generatedAt,
    generatedById: row.generatedById,
    // Re-checked like every other id: a narrower viewer is not told who was chosen if they may not see that person.
    chosenEmployeeId: row.chosenEmployeeId && visibleEmployeeIds.has(row.chosenEmployeeId) ? row.chosenEmployeeId : null,
    decidedAt: row.decidedAt,
    decidedById: row.decidedById,
    decisionReason: row.decisionReason,
  };
}

/** Every employee id a recommendation mentions (candidates, blocked, chosen). */
export function mentionedEmployeeIds(row: DispatchRecommendation): string[] {
  const blocking = row.blockingReasons as unknown as BlockingReasons | null;
  return [...new Set([...storedCandidates(row).ranked.map((candidate) => candidate.employeeId), ...Object.keys(blocking ?? {}), ...(row.chosenEmployeeId ? [row.chosenEmployeeId] : [])])];
}

/** Which of `employeeIds` the actor may see (`employees.view`, any field set). One query. */
export async function visibleEmployeeIdSet(tx: TenantTx, actor: Actor, employeeIds: readonly string[]): Promise<Set<string>> {
  if (employeeIds.length === 0) return new Set();
  const visible = await scopeFilterInTx(tx, actor, "employees.view", employeeScopeColumns);
  const rows = await tx.employee.findMany({ where: { AND: [visible, { tenantId: actor.tenantId, id: { in: [...employeeIds] } }] }, select: { id: true } });
  return new Set(rows.map((row) => row.id));
}

/** `recommendationView` for a viewer: resolves visibility of every mentioned employee in one query. */
export async function viewRecommendationsFor(tx: TenantTx, actor: Actor, rows: DispatchRecommendation[]): Promise<RecommendationView[]> {
  const visible = await visibleEmployeeIdSet(tx, actor, [...new Set(rows.flatMap(mentionedEmployeeIds))]);
  return rows.map((row) => recommendationView(row, visible));
}

/** Prisma JSON input (typed once, here). */
export const candidatesJson = (stored: StoredCandidates): Prisma.InputJsonValue => stored as unknown as Prisma.InputJsonValue;
export const blockingJson = (blocking: BlockingReasons): Prisma.InputJsonValue => blocking as unknown as Prisma.InputJsonValue;
export { SCORING_VERSION };

/**
 * Authorizes `permission` over the job (capability first, then over the job's service area / assignees)
 * and returns its resource reference. A job outside the caller's scope is a 404, never a 403.
 */
export async function authorizeOverJob(tx: TenantTx, actor: Actor, permission: string, jobId: string): Promise<ResourceRef> {
  await enforceInTx(tx, actor, permission);
  const ref = await jobResourceRef(tx, actor.tenantId, jobId);
  if (!ref) throw new NotFoundError();
  await enforceInTx(tx, actor, permission, ref);
  return ref;
}
